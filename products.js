/*
 * Shared helpers
 */

window.SVD_PRODUCTS = window.SVD_PRODUCTS || {};

window.SVD_PRODUCT_LIST = Object.keys(window.SVD_PRODUCTS).map(function (id) {
    return Object.assign(
        { id: id },
        window.SVD_PRODUCTS[id]
    );
});


window.getSVDProduct = function (productId) {
    var product = window.SVD_PRODUCTS[productId];

    if (!product) {
        return null;
    }

    return Object.assign(
        { id: productId },
        product
    );
};


window.getSVDProductsByCategory = function (category) {

    if (!category || category.toLowerCase() === "all") {
        return window.SVD_PRODUCT_LIST.slice();
    }

    var normalized = category.toLowerCase();

    return window.SVD_PRODUCT_LIST.filter(function (product) {
        return String(product.category).toLowerCase() === normalized;
    });

};
